# A search path is a Postgres idea; the sqlite the test runner builds has no
# schemas and rejects the option outright.
_db_options = (
    {"options": f"-c search_path={DB_SCHEMA},core"}
    if DB_SCHEMA and "postgresql" in _db_engine
    else {}
)

